const LATEST_RELEASE_ENDPOINT = 'https://api.github.com/repos/vargamateistvan/dayboard/releases/latest'
export const RELEASES_PAGE_URL = 'https://github.com/vargamateistvan/dayboard/releases'

export interface ReleaseNoteSection {
  readonly title: string
  readonly items: string[]
}

export interface Release {
  readonly version: string
  readonly publishedAt: string
  readonly url: string
  readonly sections: ReleaseNoteSection[]
}

interface GitHubRelease {
  readonly tag_name?: string
  readonly published_at?: string | null
  readonly html_url?: string
  readonly body?: string | null
}

// Release bodies are generated by CI as "### Heading" blocks of "- item (sha)" lines.
export function parseReleaseNotes(body: string): ReleaseNoteSection[] {
  const sections: { title: string; items: string[] }[] = []

  for (const rawLine of body.split('\n')) {
    const line = rawLine.trim()
    const heading = /^#{1,6}\s+(.+)$/.exec(line)
    if (heading) {
      sections.push({ title: heading[1], items: [] })
      continue
    }

    const item = /^[-*]\s+(.+)$/.exec(line)
    if (item) {
      if (sections.length === 0) {
        sections.push({ title: 'Changes', items: [] })
      }
      sections[sections.length - 1].items.push(item[1].replace(/\s*\([0-9a-f]{7,40}\)$/i, ''))
    }
  }

  return sections.filter((section) => section.items.length > 0)
}

// GitHub's "latest" endpoint already skips drafts and prereleases.
export async function fetchLatestRelease(signal?: AbortSignal): Promise<Release | null> {
  const response = await fetch(LATEST_RELEASE_ENDPOINT, {
    headers: { Accept: 'application/vnd.github+json' },
    signal,
  })

  if (response.status === 404) {
    return null
  }

  if (!response.ok) {
    throw new Error(`Failed to load latest release (${response.status})`)
  }

  const release = (await response.json()) as GitHubRelease
  if (!release.tag_name) {
    return null
  }

  return {
    version: release.tag_name,
    publishedAt: release.published_at ?? '',
    url: release.html_url ?? RELEASES_PAGE_URL,
    sections: parseReleaseNotes(release.body ?? ''),
  }
}
