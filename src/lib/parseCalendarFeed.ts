import ICAL, { type Event as ICalEvent, type Property as ICalProperty, type Time as ICalTime } from 'ical.js'

export interface CalendarPerson {
  name: string
  email?: string
  responseStatus?: string
}

export interface CalendarEvent {
  title: string
  start: Date
  end: Date
  allDay: boolean
  eventUrl?: string
  notes?: string
  location?: string
  organizer?: CalendarPerson
  attendees?: CalendarPerson[]
  calendarColor?: string
  /** iCal UID, shared by all occurrences of a recurring event. */
  uid?: string
  /** The feed the event came from (set by the calendar widget). */
  calendarId?: string
}

export interface CalendarRange {
  start: Date
  end: Date
}

function dayRange(referenceDate = new Date()): CalendarRange {
  const start = new Date(
    referenceDate.getFullYear(),
    referenceDate.getMonth(),
    referenceDate.getDate(),
    0,
    0,
    0,
    0,
  )
  const end = new Date(
    referenceDate.getFullYear(),
    referenceDate.getMonth(),
    referenceDate.getDate(),
    23,
    59,
    59,
    999,
  )
  return { start, end }
}

// End times are exclusive (iCal DTEND): an event ending at midnight, or an
// all-day event whose DTEND is today, does not belong to today. Zero-length
// events count when they start inside the range.
function isInRange(start: Date, end: Date, range: CalendarRange): boolean {
  if (start > range.end) return false
  return end > range.start || (end.getTime() === start.getTime() && start >= range.start)
}

const DAY_MS = 86_400_000
// Safety cap for runaway rules (e.g. FREQ=MINUTELY with no end).
const MAX_RECURRENCE_ITERATIONS = 200_000

const timeZoneFormatters = new Map<string, Intl.DateTimeFormat | null>()

function getTimeZoneFormatter(timeZone: string): Intl.DateTimeFormat | null {
  if (!timeZoneFormatters.has(timeZone)) {
    try {
      timeZoneFormatters.set(
        timeZone,
        new Intl.DateTimeFormat('en-US', {
          timeZone,
          hourCycle: 'h23',
          year: 'numeric',
          month: 'numeric',
          day: 'numeric',
          hour: 'numeric',
          minute: 'numeric',
          second: 'numeric',
        }),
      )
    } catch {
      timeZoneFormatters.set(timeZone, null)
    }
  }
  return timeZoneFormatters.get(timeZone) ?? null
}

function timeZoneOffsetMs(instant: number, formatter: Intl.DateTimeFormat): number {
  const parts = formatter.formatToParts(new Date(instant))
  const get = (type: Intl.DateTimeFormatPartTypes) => Number(parts.find((part) => part.type === type)?.value)
  const wallAsUtc = Date.UTC(get('year'), get('month') - 1, get('day'), get('hour'), get('minute'), get('second'))
  return wallAsUtc - Math.floor(instant / 1000) * 1000
}

/**
 * Converts an ICAL.Time to a Date. Feeds may reference a TZID without
 * including its VTIMEZONE; ical.js then treats the time as local, so for IANA
 * zone names the wall-clock time is converted with Intl instead.
 */
function toDate(time: ICalTime, fallbackTzid?: string): Date {
  // Occurrence times generated by ical.js drop the TZID, so callers pass the
  // one from the event's DTSTART/DTEND.
  const tzid = time.timezone ?? fallbackTzid
  const formatter = !time.isDate && tzid && !ICAL.TimezoneService.has(tzid) ? getTimeZoneFormatter(tzid) : null
  if (!formatter) return time.toJSDate()

  const wallAsUtc = Date.UTC(time.year, time.month - 1, time.day, time.hour, time.minute, time.second)
  const guess = wallAsUtc - timeZoneOffsetMs(wallAsUtc, formatter)
  // Second pass picks up a DST change between the guess and the real instant.
  return new Date(wallAsUtc - timeZoneOffsetMs(guess, formatter))
}

function normalizeTextValue(value: unknown): string | undefined {
  if (typeof value !== 'string') {
    return undefined
  }

  const trimmedValue = value.replace(/\r\n?/g, '\n').trim()
  return trimmedValue ? trimmedValue : undefined
}

function normalizeEventUrl(value: unknown): string | undefined {
  const trimmedValue = normalizeTextValue(value)
  if (!trimmedValue) {
    return undefined
  }

  try {
    const url = new URL(trimmedValue)
    if (url.protocol !== 'http:' && url.protocol !== 'https:') {
      return undefined
    }

    return url.toString()
  } catch {
    return undefined
  }
}

function extractFirstHttpUrl(value: unknown): string | undefined {
  if (typeof value !== 'string') {
    return undefined
  }

  const match = value.match(/https?:\/\/[^\s<>"')]+/i)
  return match ? normalizeEventUrl(match[0]) : undefined
}

function stripHtml(value: string): string {
  return value
    .replace(/<br\s*\/?>/gi, '\n')
    .replace(/<\/p>/gi, '\n\n')
    .replace(/<[^>]+>/g, '')
    .replace(/&nbsp;/gi, ' ')
    .replace(/&amp;/gi, '&')
    .replace(/&lt;/gi, '<')
    .replace(/&gt;/gi, '>')
    .replace(/&quot;/gi, '"')
    .replace(/&#39;/gi, "'")
    .replace(/\n{3,}/g, '\n\n')
    .trim()
}

function normalizeContactValue(value: unknown): string | undefined {
  const trimmedValue = normalizeTextValue(value)
  if (!trimmedValue) {
    return undefined
  }

  return trimmedValue.toLowerCase().startsWith('mailto:') ? trimmedValue.slice('mailto:'.length) : trimmedValue
}

function parseCsvLine(line: string): string[] {
  const values: string[] = []
  let current = ''
  let inQuotes = false

  for (let index = 0; index < line.length; index += 1) {
    const char = line[index]

    if (char === '"') {
      if (inQuotes && line[index + 1] === '"') {
        current += '"'
        index += 1
        continue
      }

      inQuotes = !inQuotes
      continue
    }

    if (char === ',' && !inQuotes) {
      values.push(current.trim())
      current = ''
      continue
    }

    current += char
  }

  values.push(current.trim())
  return values
}

function getEventNotes(event: ICalEvent): string | undefined {
  const plainDescription = normalizeTextValue(event.component.getFirstPropertyValue('description'))
  if (plainDescription) {
    return plainDescription
  }

  const htmlDescription = normalizeTextValue(event.component.getFirstPropertyValue('x-alt-desc'))
  return htmlDescription ? stripHtml(htmlDescription) : undefined
}

function parsePersonProperty(property: ICalProperty | null): CalendarPerson | undefined {
  if (!property) {
    return undefined
  }

  const email = normalizeContactValue(property.getFirstValue())
  const name = normalizeTextValue(property.getParameter('cn')) ?? email
  if (!name) {
    return undefined
  }

  const responseStatus = normalizeTextValue(property.getParameter('partstat'))

  return {
    name,
    ...(email && email !== name ? { email } : {}),
    ...(responseStatus ? { responseStatus } : {}),
  }
}

function getEventAttendees(event: ICalEvent): CalendarPerson[] | undefined {
  const attendees = event.component
    .getAllProperties('attendee')
    .map((property) => parsePersonProperty(property))
    .filter((attendee): attendee is CalendarPerson => attendee !== undefined)

  return attendees.length > 0 ? attendees : undefined
}

function getEventUrl(event: ICalEvent): string | undefined {
  const directUrl = normalizeEventUrl(event.component.getFirstPropertyValue('url'))

  if (directUrl) {
    return directUrl
  }

  const descriptionUrl = extractFirstHttpUrl(event.component.getFirstPropertyValue('description'))
  if (descriptionUrl) {
    return descriptionUrl
  }

  const htmlDescriptionUrl = extractFirstHttpUrl(event.component.getFirstPropertyValue('x-alt-desc'))
  if (htmlDescriptionUrl) {
    return htmlDescriptionUrl
  }

  const locationUrl = extractFirstHttpUrl(event.component.getFirstPropertyValue('location'))
  if (locationUrl) {
    return locationUrl
  }

  return extractFirstHttpUrl(event.component.getFirstPropertyValue('attach'))
}

function getEventMetadata(event: ICalEvent): Pick<
  CalendarEvent,
  'eventUrl' | 'notes' | 'location' | 'organizer' | 'attendees' | 'uid'
> {
  return {
    eventUrl: getEventUrl(event),
    notes: getEventNotes(event),
    location: normalizeTextValue(event.component.getFirstPropertyValue('location')),
    organizer: parsePersonProperty(event.component.getFirstProperty('organizer')),
    attendees: getEventAttendees(event),
    uid: normalizeTextValue(event.uid),
  }
}

function toCalendarEvent(
  title: string,
  start: Date,
  end: Date,
  allDay: boolean,
  metadata: Pick<CalendarEvent, 'eventUrl' | 'notes' | 'location' | 'organizer' | 'attendees' | 'uid'>,
  range: CalendarRange,
): CalendarEvent | null {
  return isInRange(start, end, range) ? { title, start, end, allDay, ...metadata } : null
}

function isCancelledEvent(event: ICalEvent): boolean {
  return event.component.getFirstPropertyValue('status') === 'CANCELLED'
}

function hasDirectException(event: ICalEvent, occurrence: ICalTime): boolean {
  return (
    occurrence.toString() in event.exceptions ||
    occurrence.convertToZone(ICAL.Timezone.utcTimezone).toString() in event.exceptions
  )
}

function parseRecurringEvent(event: ICalEvent, range: CalendarRange): CalendarEvent[] {
  const iterator = event.iterator()
  const events: CalendarEvent[] = []
  const durationMs = Math.max(0, toDate(event.endDate).getTime() - toDate(event.startDate).getTime())

  const startTzid = event.startDate.timezone
  const endTzid = event.endDate.timezone ?? startTzid

  const addOccurrence = (item: ICalEvent, startTime: ICalTime, endTime: ICalTime) => {
    if (isCancelledEvent(item)) return
    const nextEvent = toCalendarEvent(
      item.summary,
      toDate(startTime, item.startDate.timezone ?? startTzid),
      toDate(endTime, item.endDate.timezone ?? endTzid),
      startTime.isDate,
      getEventMetadata(item),
      range,
    )
    if (nextEvent) events.push(nextEvent)
  }

  // Walk occurrences in their original order and stop once the original start
  // passes the range. Iterations are not capped at the range start, so rules
  // that began years ago still reach today.
  for (let iterations = 0; iterations < MAX_RECURRENCE_ITERATIONS; iterations += 1) {
    const occurrenceTime = iterator.next()
    if (!occurrenceTime) break

    const originalStart = toDate(occurrenceTime, startTzid)
    if (originalStart > range.end) break

    // Moved or edited occurrences are added below at their own times.
    if (hasDirectException(event, occurrenceTime)) continue

    // Cheap skip for occurrences that end well before the range (a day of
    // slack covers DST shifts and all-day events).
    if (originalStart.getTime() + durationMs + DAY_MS < range.start.getTime()) continue

    const details = event.getOccurrenceDetails(occurrenceTime)
    addOccurrence(details.item, details.startDate, details.endDate)
  }

  for (const exception of Object.values(event.exceptions)) {
    addOccurrence(exception, exception.startDate, exception.endDate)
  }

  return events
}

export function parseIcs(text: string, range = dayRange()): CalendarEvent[] {
  if (!text || !text.includes('BEGIN:VEVENT')) return []

  try {
    const calendar = new ICAL.Component(ICAL.parse(text))
    const sourceEvents = calendar.getAllSubcomponents('vevent').map((component) => new ICAL.Event(component))
    const eventsByUid = new Map<string, ICalEvent>()
    const deferredExceptions: ICalEvent[] = []
    const calendarEvents: CalendarEvent[] = []

    for (const [index, event] of sourceEvents.entries()) {
      if (event.isRecurrenceException()) {
        const parentEvent = event.uid ? eventsByUid.get(event.uid) : undefined
        if (parentEvent) {
          parentEvent.relateException(event)
        } else {
          deferredExceptions.push(event)
        }
        continue
      }

      eventsByUid.set(event.uid || `event-${index}`, event)
    }

    for (const event of deferredExceptions) {
      const parentEvent = event.uid ? eventsByUid.get(event.uid) : undefined
      if (parentEvent) {
        parentEvent.relateException(event)
      } else {
        eventsByUid.set(`${event.uid}:${event.recurrenceId?.toString() ?? 'exception'}`, event)
      }
    }

    for (const event of eventsByUid.values()) {
      if (event.isRecurring()) {
        calendarEvents.push(...parseRecurringEvent(event, range))
        continue
      }

      if (isCancelledEvent(event)) {
        continue
      }

      const nextEvent = toCalendarEvent(
        event.summary,
        toDate(event.startDate),
        toDate(event.endDate),
        event.startDate.isDate,
        getEventMetadata(event),
        range,
      )

      if (nextEvent) {
        calendarEvents.push(nextEvent)
      }
    }

    return calendarEvents.sort((a, b) => a.start.getTime() - b.start.getTime())
  } catch {
    return []
  }
}

const DATE_ONLY_PATTERN = /^(\d{4})-(\d{2})-(\d{2})$/

/** `YYYY-MM-DD` as local midnight (`new Date()` would read it as UTC). */
function parseLocalDateOnly(value: string | undefined): Date | null {
  const match = value?.trim().match(DATE_ONLY_PATTERN)
  return match ? new Date(Number(match[1]), Number(match[2]) - 1, Number(match[3])) : null
}

function addDays(date: Date, days: number): Date {
  return new Date(date.getFullYear(), date.getMonth(), date.getDate() + days)
}

// Date-only rows become all-day events; a date-only End is the last day (inclusive).
export function parseCsv(text: string, range = dayRange()): CalendarEvent[] {
  if (!text.trim()) return []
  const lines = text.trim().split(/\r?\n/)
  if (lines.length < 2) return []

  const header = parseCsvLine(lines[0].replace(/^\uFEFF/, '')).map((h) => h.trim().toLowerCase())
  const titleIdx = header.indexOf('title')
  const startIdx = header.indexOf('start')
  const endIdx = header.indexOf('end')
  const urlIdx = header.indexOf('url')
  const linkIdx = header.indexOf('link')
  const locationIdx = header.indexOf('location')
  const descriptionIdx = header.indexOf('description')
  const notesIdx = header.indexOf('notes')
  const guestsIdx = header.indexOf('guests')
  const inviteesIdx = header.indexOf('invitees')
  const organizerIdx = header.indexOf('organizer')

  if (titleIdx === -1 || startIdx === -1) return []

  const events: CalendarEvent[] = []
  for (let i = 1; i < lines.length; i++) {
    const cols = parseCsvLine(lines[i])
    try {
      const title = normalizeTextValue(cols[titleIdx]) ?? ''
      const startDateOnly = parseLocalDateOnly(cols[startIdx])
      const allDay = startDateOnly !== null
      const start = startDateOnly ?? new Date(cols[startIdx])
      const endDateOnly = endIdx !== -1 ? parseLocalDateOnly(cols[endIdx]) : null
      const end = allDay
        ? addDays(endDateOnly && endDateOnly >= start ? endDateOnly : start, 1)
        : endIdx !== -1 && cols[endIdx]
          ? new Date(cols[endIdx])
          : new Date(start.getTime() + 3600_000)
      const rawUrl =
        urlIdx !== -1 ? cols[urlIdx]
        : linkIdx !== -1 ? cols[linkIdx]
        : locationIdx !== -1 ? extractFirstHttpUrl(cols[locationIdx])
        : descriptionIdx !== -1 ? extractFirstHttpUrl(cols[descriptionIdx])
        : undefined
      const eventUrl = normalizeEventUrl(rawUrl)
      const location = locationIdx !== -1 ? normalizeTextValue(cols[locationIdx]) : undefined
      const notes =
        notesIdx !== -1 ? normalizeTextValue(cols[notesIdx])
        : descriptionIdx !== -1 ? normalizeTextValue(cols[descriptionIdx])
        : undefined
      const attendeeNames =
        guestsIdx !== -1 ? cols[guestsIdx]
        : inviteesIdx !== -1 ? cols[inviteesIdx]
        : undefined
      const attendees = attendeeNames
        ?.split(/[;|]/)
        .map((entry) => normalizeTextValue(entry))
        .filter((entry): entry is string => Boolean(entry))
        .map((name) => ({ name }))
      const organizerName = organizerIdx !== -1 ? normalizeTextValue(cols[organizerIdx]) : undefined
      if (isNaN(start.getTime())) continue
      if (isInRange(start, end, range)) {
        events.push({
          title,
          start,
          end,
          allDay,
          eventUrl,
          location,
          notes,
          ...(organizerName ? { organizer: { name: organizerName } } : {}),
          ...(attendees && attendees.length > 0 ? { attendees } : {}),
        })
      }
    } catch {
      // skip malformed rows
    }
  }

  return events.sort((a, b) => a.start.getTime() - b.start.getTime())
}

export function parseCalendarFeed(text: string, range = dayRange()): CalendarEvent[] {
  if (!text || !text.trim()) return []
  if (text.includes('BEGIN:VCALENDAR') || text.includes('BEGIN:VEVENT')) {
    return parseIcs(text, range)
  }
  return parseCsv(text, range)
}
